"""Deterministic report (spec Section 5, outputs 1, 2 and 6).

Writes, into one output folder:
    report.md            summary, setting depths and kick tolerance, a
                         design-factor table per string, assumptions list
    plots/*.png          pressure window for the well; burst, collapse and
                         axial load lines per string over its rating lines
    design_factors.csv   every design-factor row, for spreadsheets

Every table is followed by one sentence that says what it means for the well
(CLAUDE.md rule 8), and every report carries the field-use disclaimer (rule 7).
"""

from __future__ import annotations

import csv
import math
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

from . import __version__  # noqa: E402
from . import ratings as rt  # noqa: E402
from .design import StringCheck, WellCheck  # noqa: E402
from .loads import StringLoads  # noqa: E402
from .optimize import Optimization  # noqa: E402
from .reliability import SWEEP_TARGETS, ShoeMove, StringReliability  # noqa: E402

PF_FLOOR = 1e-12  # smaller Pf values are shown as "< 1e-12"
BETA_CAP = 8.0

DISCLAIMER = ("Student design tool. Not for field use without review by a licensed engineer "
              "and the operator's own standards.")
CHECKS = ("burst", "collapse", "tension", "compression", "triaxial")


def write_report(result: WellCheck, out_dir: str | Path,
                 reliability: dict[str, StringReliability] | None = None,
                 shoe_moves: list[ShoeMove] | None = None,
                 optimization: Optimization | None = None) -> Path:
    """Write the report, plots and CSV; returns report.md's path.

    With `reliability`, adds the probability-of-failure tables (spec output 3);
    with `optimization`, the optimized design, target sweep and reference
    comparison (output 4).
    """
    out = Path(out_dir)
    (out / "plots").mkdir(parents=True, exist_ok=True)
    plot_window(result, out / "plots" / "pressure_window.png")
    for g in result.geometries:
        plot_string(result, g.name, out / "plots" / f"loads_{_slug(g.name)}.png")
    write_csv(result, out / "design_factors.csv")
    path = out / "report.md"
    path.write_text(render_markdown(result, reliability, shoe_moves, optimization), encoding="utf-8",
                    newline="\n")
    return path


# --- Markdown ------------------------------------------------------------------------------

def render_markdown(r: WellCheck, reliability: dict[str, StringReliability] | None = None,
                    shoe_moves: list[ShoeMove] | None = None, optimization: Optimization | None = None) -> str:
    w = r.well
    lines = [f"# Casing design check: {w.well.name}", "", f"> {DISCLAIMER}", ""]
    if w.meta.synthetic:
        lines += ["> **Synthetic well.** All inputs are generated test data, not from any real well.", ""]
    lines += [f"Generated by casingrel {__version__}. Design checked: "
              f"**{r.design_name or 'none (loads only)'}**. Units: psi, ft, in, lbf, ppg, degF. "
              "Depths are from KB.", ""]
    lines += _summary(r)
    if optimization is not None:
        lines += _optimization(optimization)
    lines += _depths(r, shoe_moves)
    if reliability:
        lines += _reliability(r, reliability)
    lines += ["## Pressure window", "", "![Pressure window](plots/pressure_window.png)", "",
              "Pore pressure and fracture gradient set the mud window; each string's mud and shoe "
              "must sit inside it.", ""]
    for g in r.geometries:
        lines += _string_section(r, g.name)
    extra = []
    for rel in (reliability or {}).values():
        extra += rel.notes
    if optimization is not None:
        extra += optimization.notes
        for s in optimization.strings.values():
            extra += s.notes
    lines += _assumptions(r, extra)
    return "\n".join(lines) + "\n"


def _summary(r: WellCheck) -> list[str]:
    rows = []
    for g in r.geometries:
        c = r.checks.get(g.name)
        if c is None:
            rows.append(f"| {g.name} | {g.od_in:g} | {g.shoe_md_ft:,.0f} / {g.shoe_tvd_ft:,.0f} | not checked | - | - |")
            continue
        worst = _worst(c)
        status = "PASS" if c.ok else "**FAIL**"
        gov = (f"{worst.check}, {worst.case} ({worst.design_factor:.2f} vs {worst.required:g})"
               if worst else "-")
        rows.append(f"| {g.name} | {c.design.label} | {g.shoe_md_ft:,.0f} / {g.shoe_tvd_ft:,.0f} | {status} | "
                    f"{gov} | {_fmt_ps(c)} |")
    out = ["## Summary", "", "| String | Pipe | Shoe MD / TVD (ft) | Result | Governing (DF vs required) | "
           "Max frac surface pressure (psi) |", "|---|---|---|---|---|---|", *rows, ""]
    failing = [c.string for c in r.checks.values() if not c.ok]
    unchecked = [g.name for g in r.geometries if g.name not in r.checks]
    if failing:
        out.append(f"The design does not meet the design factors in: {', '.join(failing)}. "
                   "Those strings need a heavier weight, a stronger grade, or a change to the load case.")
    elif r.checks:
        out.append("Every checked string meets the design factors in every load case.")
    if unchecked:
        out.append(f"No pipe was assigned to {', '.join(unchecked)}, so only their loads are shown.")
    return out + [""]


def _depths(r: WellCheck, shoe_moves: list[ShoeMove] | None = None) -> list[str]:
    d = r.depths
    out = ["## Setting depths and kick tolerance", "",
           "| String | Shoe TVD (ft) | Chosen by program | Mud (ppg) | Kick tolerance (ppg) | Required (ppg) | OK |",
           "|---|---|---|---|---|---|---|"]
    kt = {k.string: k for k in d.kick_tolerance}
    for g in r.geometries:
        k = kt.get(g.name)
        out.append(f"| {g.name} | {g.shoe_tvd_ft:,.0f} | {'yes' if g.name in d.chosen_tvd_ft else 'no'} | "
                   f"{g.mud_ppg:.1f} | {f'{k.tolerance_ppg:.2f}' if k else '-'} | "
                   f"{f'{k.required_ppg:.2f}' if k else '-'} | {'-' if k is None else ('yes' if k.ok else '**no**')} |")
    bad = [k.string for k in d.kick_tolerance if not k.ok]
    if bad:
        out.append(f"\nKick tolerance is too low at: {', '.join(bad)}. A kick from the next section could "
                   "break down that shoe; set it deeper or the next shoe shallower.")
    else:
        out.append("\nEvery shoe can take the required kick from the section below it without breaking down.")
    if shoe_moves:
        out += ["", "| String | Shoe TVD (ft) | Next shoe TVD (ft) | Share of samples where the shoe must move |",
                "|---|---|---|---|"]
        out += [f"| {m.string} | {m.shoe_tvd_ft:,.0f} | {m.next_td_tvd_ft:,.0f} | {m.probability:.1%} |"
                for m in shoe_moves]
        worst = max(shoe_moves, key=lambda m: m.probability)
        out.append(f"\nWith pore pressure and fracture gradient sampled ({worst.n:,} samples), the {worst.string} "
                   f"shoe would have to move shallower in {worst.probability:.1%} of cases.")
    return out + [""]


def _string_section(r: WellCheck, name: str) -> list[str]:
    g = next(x for x in r.geometries if x.name == name)
    c = r.checks.get(name)
    sl = r.loads[name]
    head = [f"## {name}", "",
            f"{g.kind.capitalize()}, {g.od_in:g}-in in {g.hole_in:g}-in hole; top {g.top_md_ft:,.0f} ft MD, "
            f"shoe {g.shoe_md_ft:,.0f} ft MD / {g.shoe_tvd_ft:,.0f} ft TVD, TOC {g.toc_md_ft:,.0f} ft MD, "
            f"run in {g.mud_ppg:.1f} ppg mud.", ""]
    if not sl.cases and c is None:
        return head + ["No load cases apply to this string.", ""]
    plot = [f"![{name} loads](plots/loads_{_slug(name)}.png)", ""]
    if c is None:
        return head + _loads_only_table(sl) + plot
    req = r.well.design_factors
    cases = list(dict.fromkeys(row.case for row in c.rows))
    table = [f"Pipe: **{c.design.label}** ("
             + "; ".join(f"{p.label}: wall {p.wall_in:.3f} in, D/t {p.dt:.2f}, Y_p {p.yield_psi:,.0f} psi"
                         for p in c.design.pipes) + ").", "",
             "| Case | " + " | ".join(f"{k} (≥{getattr(req, k):g})" for k in CHECKS) + " |",
             "|---|" + "---|" * len(CHECKS)]
    for case in cases:
        cells = []
        for k in CHECKS:
            row = next((x for x in c.rows if x.case == case and x.check == k), None)
            cells.append(_cell(row))
        table.append(f"| {case} | " + " | ".join(cells) + " |")
    worst = _worst(c)
    table.append("")
    if c.ok:
        table.append(f"This pipe meets every design factor; the tightest margin is {worst.check} under "
                     f"{worst.case} at {worst.md_ft:,.0f} ft MD ({worst.design_factor:.2f} vs {worst.required:g}).")
    else:
        fails = [x for x in c.rows if not x.ok]
        detail = "; ".join(f"{x.check} under {x.case} at {x.md_ft:,.0f} ft MD ({x.design_factor:.2f})" for x in fails)
        table.append(f"This pipe fails {len(fails)} check(s): {detail}.")
    if c.max_surface_treating_psi is not None:
        table.append(f"At its burst design factor this string can take a surface treating pressure of up to "
                     f"{c.max_surface_treating_psi:,.0f} psi (burst only).")
    return head + table + [""] + plot


def _loads_only_table(sl: StringLoads) -> list[str]:
    out = ["| Case | Mode | Max net load (psi) | at MD (ft) |", "|---|---|---|---|"]
    for case in sl.cases:
        i = int(np.argmax(case.load_psi))
        out.append(f"| {case.name} | {case.mode} | {case.load_psi[i]:,.0f} | {case.md_ft[i]:,.0f} |")
    return out + ["", "No pipe is assigned, so these are the loads any pipe for this string must carry.", ""]


def _assumptions(r: WellCheck, extra: list[str] | None = None) -> list[str]:
    """One-page list of every placeholder, extrapolated depth and warning (spec output 6)."""
    items = list(r.well.placeholders()) + r.profiles.warnings + r.depths.warnings + r.notes + list(extra or [])
    for sl in r.loads.values():
        items += sl.notes
    for c in r.checks.values():
        items += c.notes
    items = list(dict.fromkeys(items))
    groups = {"Placeholders and defaults": [], "Extrapolated depths": [], "Warnings and limits": []}
    for it in items:
        if "extrapolated" in it:
            groups["Extrapolated depths"].append(it)
        elif "placeholder" in it or "default" in it:
            groups["Placeholders and defaults"].append(it)
        else:
            groups["Warnings and limits"].append(it)
    out = ["## Assumptions and warnings", "",
           "Every value the program assumed, and every warning it raised. Check these before trusting the results.", ""]
    for title, its in groups.items():
        out += [f"### {title}", ""] + ([f"- {x}" for x in its] or ["- none"]) + [""]
    return out


def _reliability(r: WellCheck, rel: dict[str, StringReliability]) -> list[str]:
    """Probability of failure per string, case and check (spec output 3)."""
    target = r.well.reliability_target_pf
    out = ["## Probability of failure", "",
           f"Target: Pf ≤ {target:g} per load case and check. Pf comes from Monte Carlo when its "
           "coefficient of variation is ≤ 10%, otherwise from FORM. The API TR 5C3 resistance model is used, "
           "so these values are conservative; pipe statistics marked as placeholders below make them provisional.",
           ""]
    for name, sr in rel.items():
        shown = [x for x in sr.rows if x.pf >= PF_FLOOR]
        out += [f"### {name}: {sr.design.label}", "",
                "| Case | Check | Pf | 95% CI (MC) | β | Method |", "|---|---|---|---|---|---|"]
        for x in sorted(shown, key=lambda x: -x.pf):
            ci = f"{x.mc_ci[0]:.1e} – {x.mc_ci[1]:.1e}" if x.has_mc else "-"
            flag = " ✗" if x.pf > target else ""
            out.append(f"| {x.case} | {x.check} | {_fmt_pf(x.pf)}{flag} | {ci} | {_fmt_beta(x.beta)} | {x.method} |")
        hidden = len(sr.rows) - len(shown)
        lo, hi = sr.system_bounds
        gov = sr.governing
        out.append("")
        if hidden:
            out.append(f"{hidden} other limit states have Pf < {PF_FLOOR:g}.")
        verdict = "meets" if sr.meets(target) else "does **not** meet"
        out.append(f"This string {verdict} the target; the governing failure mode is {gov.check} under {gov.case} "
                   f"(Pf {_fmt_pf(gov.pf)}). The system Pf lies between {_fmt_pf(lo)} and {_fmt_pf(hi)}.")
        imp = sr.importance(gov.case, gov.check)
        if imp:
            top = sorted(imp.items(), key=lambda kv: -abs(kv[1]))[:3]
            out.append("Inputs driving it (FORM α², sign shows direction towards failure): "
                       + ", ".join(f"{k} {v:+.2f}" for k, v in top) + ".")
        out.append("")
    out += ["### Target sweep", "", "| Target Pf | " + " | ".join(rel) + " |", "|---|" + "---|" * len(rel)]
    for t in SWEEP_TARGETS:
        out.append(f"| {t:g} | " + " | ".join("meets" if sr.meets(t) else "**fails**" for sr in rel.values()) + " |")
    out += ["", "The sweep shows whether each string's verdict depends on the choice of target (spec 4.3).", ""]
    return out


def _optimization(o: Optimization) -> list[str]:
    """Optimized design, target sweep and reference comparison (spec output 4)."""
    out = ["## Optimized design", "",
           f"Cheapest design per string from `{o.catalog_path.name}` that passes the deterministic check and has "
           f"Pf ≤ {o.target_pf:g} in every load case (single pipes and two-section tapered strings, crossover "
           "on a 100-ft grid).", "",
           "| String | Chosen design | Cost | Max Pf | Governing | Designs searched |", "|---|---|---|---|---|---|"]
    for name, s in o.strings.items():
        c = s.chosen
        if c is None:
            best = f" (closest: {s.best_effort.design.label}, DF ratio {s.best_effort.worst_df_ratio:.2f})" \
                if s.best_effort else ""
            out.append(f"| {name} | **none feasible**{best} | - | - | - | {s.designs_considered} |")
        else:
            out.append(f"| {name} | {c.design.label} | {_fmt_cost(c.cost, s.mode)} | {_fmt_pf(c.max_pf)} | "
                       f"{c.governing[1]}, {c.governing[0]} | {s.designs_considered} |")
    units = {s.unit for s in o.strings.values()}
    out.append("")
    out.append(f"Costs are in {', '.join(sorted(units))}.")
    infeasible = [n for n, s in o.strings.items() if s.chosen is None]
    if infeasible:
        out.append(f"No catalog pipe works for {', '.join(infeasible)}; the catalog needs heavier or stronger pipe "
                   "for that size before the program can choose a design.")
    else:
        out.append("Every string has a design that meets both the design factors and the reliability target.")
    targets = sorted({t for s in o.strings.values() for t in s.by_target}, reverse=True)
    out += ["", "### Choice by target (FORM screen)", "",
            "| Target Pf | " + " | ".join(o.strings) + " |", "|---|" + "---|" * len(o.strings)]
    for t in targets:
        cells = []
        for s in o.strings.values():
            c = s.by_target.get(t)
            cells.append("none" if c is None else f"{c.design.label} ({_fmt_cost(c.cost, s.mode)})")
        out.append(f"| {t:g} | " + " | ".join(cells) + " |")
    out += ["", "A stricter target buys a stronger or heavier string; where the choice stays the same, the "
            "answer does not depend on the target.", ""]
    if o.references:
        out += ["### Reference designs", "",
                "| Design | String | Pipe | Cost | Deterministic | Max Pf | Note |", "|---|---|---|---|---|---|---|"]
        for ref in o.references:
            c = ref.candidate
            if c is None:
                out.append(f"| {ref.design_name} | {ref.string} | not checked | - | - | - | {ref.note or ''} |")
                continue
            mode = o.strings[ref.string].mode if ref.string in o.strings else "illustrative"
            out.append(f"| {ref.design_name} | {ref.string} | {c.design.label} | {_fmt_cost(c.cost, mode)} | "
                       f"{'pass' if c.deterministic_ok else '**fail**'} | {_fmt_pf(c.max_pf)} | {ref.note or ''} |")
        out += ["", "Each reference design is scored with the same loads, checks and reliability model as the "
                "optimized design.", ""]
    return out


def _fmt_pf(pf: float | None) -> str:
    if pf is None or (isinstance(pf, float) and math.isnan(pf)):
        return "-"
    return f"< {PF_FLOOR:g}" if pf < PF_FLOOR else f"{pf:.1e}"


def _fmt_beta(beta: float) -> str:
    if not math.isfinite(beta) or beta > BETA_CAP:
        return f"> {BETA_CAP:g}" if beta > 0 else "-"
    return f"{beta:.2f}"


def _fmt_cost(cost: float, mode: str) -> str:
    return f"${cost:,.0f}" if mode == "dollars" else f"{cost:,.0f}"


def _cell(row) -> str:
    if row is None:
        return "-"
    if math.isinf(row.design_factor):
        return "no load"
    txt = f"{row.design_factor:.2f}"
    return txt if row.ok else f"**{txt} ✗**"


def _worst(c: StringCheck):
    finite = [x for x in c.rows if math.isfinite(x.design_factor)]
    return min(finite, key=lambda x: x.design_factor / x.required) if finite else None


def _fmt_ps(c: StringCheck) -> str:
    return f"{c.max_surface_treating_psi:,.0f}" if c.max_surface_treating_psi is not None else "-"


def _slug(name: str) -> str:
    return "".join(ch if ch.isalnum() else "_" for ch in name.lower())


# --- CSV -----------------------------------------------------------------------------------

def write_csv(r: WellCheck, path: Path) -> None:
    with open(path, "w", newline="", encoding="utf-8") as fh:
        wr = csv.writer(fh)
        wr.writerow(["string", "pipe", "case", "check", "design_factor", "required", "ok", "md_ft", "tvd_ft"])
        for c in r.checks.values():
            for x in c.rows:
                wr.writerow([x.string, c.design.label, x.case, x.check,
                             "inf" if math.isinf(x.design_factor) else f"{x.design_factor:.4f}",
                             x.required, x.ok, "" if x.md_ft is None else f"{x.md_ft:.1f}",
                             "" if x.tvd_ft is None else f"{x.tvd_ft:.1f}"])


# --- Plots ----------------------------------------------------------------------------------

def plot_window(r: WellCheck, path: Path) -> None:
    """Pore, fracture, overburden, mud weights and shoes against TVD."""
    p = r.profiles
    z = np.linspace(0, p.max_tvd_ft, 400)
    fig, ax = plt.subplots(figsize=(6, 8))
    ax.plot(p.pore_ppg(z), z, label="Pore pressure")
    ax.plot(p.frac_ppg(z), z, label="Fracture gradient")
    ax.plot(p.overburden_ppg(z), z, label="Overburden", color="0.5")
    m = r.well.margins
    ax.plot(p.pore_ppg(z) + m.trip_margin_ppg, z, ":", color="C0", label="Pore + trip margin")
    ax.plot(p.frac_ppg(z) - m.kick_margin_ppg, z, ":", color="C1", label="Frac - kick margin")
    top = 0.0
    for g in sorted(r.geometries, key=lambda x: x.shoe_tvd_ft):
        if g.kind == "tieback":
            continue
        ax.plot([g.mud_ppg, g.mud_ppg], [top, g.shoe_tvd_ft], color="k", lw=2)
        ax.plot(g.mud_ppg, g.shoe_tvd_ft, "k<", ms=8)
        ax.annotate(f" {g.name}", (g.mud_ppg, g.shoe_tvd_ft), fontsize=8, va="center")
        top = g.shoe_tvd_ft
    ax.plot([], [], color="k", lw=2, label="Mud weight / shoe")
    ax.set_xlabel("Equivalent gradient (ppg)")
    ax.set_ylabel("TVD (ft)")
    ax.invert_yaxis()
    ax.grid(alpha=0.3)
    ax.legend(fontsize=8, loc="upper center")
    ax.set_title(r.well.well.name, fontsize=10)
    fig.tight_layout()
    fig.savefig(path, dpi=110)
    plt.close(fig)


def plot_string(r: WellCheck, name: str, path: Path) -> None:
    """Burst, collapse and axial load lines against MD, over the pipe's rating lines."""
    sl = r.loads[name]
    c = r.checks.get(name)
    df = r.well.design_factors
    fig, axes = plt.subplots(1, 3, figsize=(13, 6), sharey=True)
    md = sl.md_ft
    for case in sl.cases:
        if case.mode == "burst":
            axes[0].plot(case.load_psi, md, label=case.name)
        else:
            if c:
                nr = c.design.at(md)
                pe_eq = rt.equivalent_external_pressure_psi(case.p_external_psi, case.p_internal_psi, nr.od_in,
                                                           nr.wall_in)
            else:
                pe_eq = case.load_psi
            axes[1].plot(pe_eq, md, label=case.name)
    if c is not None:
        nr = c.design.at(md)
        burst = rt.burst_api_psi(nr.od_in, nr.wall_in, nr.yield_psi)
        collapse = rt.collapse_api_psi(nr.od_in, nr.wall_in, nr.yield_psi)
        body = rt.pipe_body_yield_lbf(nr.od_in, nr.wall_in, nr.yield_psi)
        for ax, rating, f in ((axes[0], burst, df.burst), (axes[1], collapse, df.collapse)):
            ax.plot(rating, md, color="k", lw=1.5, label="Rating (nominal)")
            ax.plot(rating / f, md, color="k", ls="--", lw=1, label=f"Rating / DF {f:g}")
        bend = sl.bending_stress_psi * nr.area_steel_in2
        for a in sl.axial:
            axes[2].plot(a.real_lbf + bend, md, label=a.name)
        for case in sl.cases:
            if case.name == "frac_down_casing":
                axes[2].plot(case.axial_real_lbf + bend, md, label="frac (service)")
        axes[2].plot(body, md, color="k", lw=1.5, label="Body yield")
        axes[2].plot(body / df.tension, md, color="k", ls="--", lw=1, label=f"Yield / DF {df.tension:g}")
        axes[2].axvline(0, color="0.6", lw=0.8)
    else:
        axes[2].text(0.5, 0.5, "No pipe assigned", transform=axes[2].transAxes, ha="center")
    titles = ("Burst load Pi - Pe (psi)", "Collapse load, equivalent Pe (psi)", "Axial + bending (lbf)")
    for ax, t in zip(axes, titles):
        ax.set_xlabel(t)
        ax.grid(alpha=0.3)
        if ax.get_legend_handles_labels()[0]:
            ax.legend(fontsize=7)
    axes[0].set_ylabel("MD (ft)")
    axes[0].invert_yaxis()
    label = c.design.label if c else "no pipe"
    fig.suptitle(f"{r.well.well.name}: {name} ({label})", fontsize=10)
    fig.tight_layout()
    fig.savefig(path, dpi=110)
    plt.close(fig)
